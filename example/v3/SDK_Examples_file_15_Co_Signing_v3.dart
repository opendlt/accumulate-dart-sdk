      keypair: generateKeysSigner_1Key,
      signerUrl: generateKeysSigner_1Lid.toString(),
    );
    final createAdiResult = await createAdiSigner.signSubmitAndWait(
      principal: generateKeysSigner_1Lta.toString(),
      body: TxBody.createIdentity(
        url: createAdiUrl,
        keyBookUrl: '${createAdiUrl}/book',
        publicKeyHash: generateKeysSigner_1PubHash,
      ),
      memo: 'Create ADI',
      maxAttempts: 30,
    );
    if (createAdiResult.success) {
      print('CreateIdentity SUCCESS - TxID: ${createAdiResult.txid}');
      if (createAdiResult.txid != null) {
