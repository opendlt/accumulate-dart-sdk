    // =========================================================
    // Generate Keys (Signer 3) (GenerateKeys)
    // =========================================================
    final generateKeysSigner_3Kp = await Ed25519KeyPair.generate();
    final generateKeysSigner_3Key = UnifiedKeyPair.fromEd25519(generateKeysSigner_3Kp);
    final generateKeysSigner_3Lid = await generateKeysSigner_3Kp.deriveLiteIdentityUrl();
    final generateKeysSigner_3Lta = await generateKeysSigner_3Kp.deriveLiteTokenAccountUrl();
    final generateKeysSigner_3PubKey = await generateKeysSigner_3Kp.publicKeyBytes();
    final generateKeysSigner_3PubHash = toHexString(sha256.convert(generateKeysSigner_3PubKey).bytes);
    print('Generated keypair:');
    print('  Lite Identity: ${generateKeysSigner_3Lid}');
    print('  Lite Token Account: ${generateKeysSigner_3Lta}');
    print('  Public Key Hash: ${generateKeysSigner_3PubHash}');


    // =========================================================
    // Add Signer 3 (Action: UpdateKeyPage)
    // =========================================================
    final addSigner_3Signer = SmartSigner(
      client: client.v3,
      keypair: generateKeysSigner_1Key,
      signerUrl: '${createAdiUrl}/multisig-book/1',
    );
    final addSigner_3RawOps = [{"type":"add","entry":{"keyHash":generateKeysSigner_3PubHash}}] as List;
    final addSigner_3Result = await addSigner_3Signer.signSubmitAndWait(
      principal: '${createAdiUrl}/multisig-book/1',
      body: TxBody.updateKeyPage(
        operations: addSigner_3RawOps
