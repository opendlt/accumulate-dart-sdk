    final creditMultiSigKeyPageResult = await creditMultiSigKeyPageSigner.signSubmitAndWait(
      principal: generateKeysSigner_1Lta.toString(),
      body: TxBody.addCredits(
        recipient: '${createAdiUrl}/multisig-book/1',
        amount: '500000000',
        oracle: creditMultiSigKeyPageOraclePrice,
      ),
      memo: 'Add credits',
      maxAttempts: 30,
    );
    if (creditMultiSigKeyPageResult.success) {
      print('AddCredits SUCCESS - TxID: ${creditMultiSigKeyPageResult.txid}');
      if (creditMultiSigKeyPageResult.txid != null) {
        txIds.add(MapEntry('AddCredits', creditMultiSigKeyPageResult.txid!));
      }
    } else {
      print('AddCredits FAILED: ${creditMultiSigKeyPageResult.error}');
    }


    // =========================================================
    // Wait for Multi-Sig Credits (WaitForCredits)
    // =========================================================
    print('Waiting for credits >= 1000...');
    for (var i = 0; i < 30; i++) {
      try {
        final result = await client.v3.rawCall('query', {
          'scope': '${createAdiUrl}/multisig-book/1',
          'query': {'queryType': 'default'},
        });
        final creditBalance = result['account']?['creditBalance'];
        if (creditBalance != null && (creditBalance as int) >= 1000) break;
      } catch (_) {}
      await Future.delayed(Duration(seconds: 2));
