    if (creditKeyPageResult.success) {
      print('AddCredits SUCCESS - TxID: ${creditKeyPageResult.txid}');
      if (creditKeyPageResult.txid != null) {
        txIds.add(MapEntry('AddCredits', creditKeyPageResult.txid!));
