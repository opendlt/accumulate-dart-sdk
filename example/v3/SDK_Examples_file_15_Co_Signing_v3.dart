    print('Credits reached');


    // =========================================================
    // Generate Keys (Signer 2) (GenerateKeys)
    // =========================================================
    final generateKeysSigner_2Kp = await Ed25519KeyPair.generate();
    final generateKeysSigner_2Key = UnifiedKeyPair.fromEd25519(generateKeysSigner_2Kp);
    final generateKeysSigner_2Lid = await generateKeysSigner_2Kp.deriveLiteIdentityUrl();
    final generateKeysSigner_2Lta = await generateKeysSigner_2Kp.deriveLiteTokenAccountUrl();
    final generateKeysSigner_2PubKey = await generateKeysSigner_2Kp.publicKeyBytes();
    final generateKeysSigner_2PubHash = toHexString(sha256.convert(generateKeysSigner_2PubKey).bytes);
    print('Generated keypair:');
    print('  Lite Identity: ${generateKeysSigner_2Lid}');
    print('  Lite Token Account: ${generateKeysSigner_2Lta}');
    print('  Public Key Hash: ${generateKeysSigner_2PubHash}');


    // =========================================================
    // Add Signer 2 (Action: UpdateKeyPage)
    // =========================================================
    final addSigner_2Signer = SmartSigner(
      client: client.v3,
      keypair: generateKeysSigner_1Key,
      signerUrl: '${createAdiUrl}/multisig-book/1',
    );
    final addSigner_2RawOps = [{"type":"add","entry":{"keyHash":generateKeysSigner_2PubHash}}] as List;
    final addSigner_2Result = await addSigner_2Signer.signSubmitAndWait(
      principal: '${createAdiUrl}/multisig-book/1',
      body: TxBody.updateKeyPage(
        operations: addSigner_2RawOps
            .map((op) => KeyPageOperation.fromJson(Map<String, dynamic>.from(op)))
            .toList(),
      ),
      memo: 'Update key page',
      maxAttempts: 30,
    );
    if (addSigner_2Result.success) {
      print('UpdateKeyPage SUCCESS - TxID: ${addSigner_2Result.txid}');
      if (addSigner_2Result.txid != null) {
        txIds.add(MapEntry('UpdateKeyPage', addSigner_2Result.txid!));
      }
    } else {
      print('UpdateKeyPage FAILED: ${addSigner_2Result.error}');
